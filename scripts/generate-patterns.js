async function seed() {
  console.log(`Seeding ${PATTERNS.length} patterns...`);
  const batch = db.batch();
  for (const p of PATTERNS) {
    batch.set(db.collection('patterns').doc(p.id), p);
  }
  await batch.commit();
  console.log('✅ Patterns seeded!');
  process.exit(0);
}
seed();
